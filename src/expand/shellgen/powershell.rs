//! The PowerShell init script.
//!
//! Expansion is done by PSReadLine itself, so the replacement appears in the line editor *before*
//! Enter — history, Ctrl+R and tab completion all keep working, which is the whole reason to
//! prefer this over the terminal-side layer.
//!
//! Aliases are defined as **functions**, not `Set-Alias`: a PowerShell alias cannot carry
//! arguments, so `Set-Alias gs "git status"` is a syntax error rather than a shortcut.

pub const SCRIPT: &str = r#"# Generated by Nyx. Edits are overwritten whenever the config changes.
#
# Loaded with: powershell -NoExit -Command ". <this file>"
# Nyx passes NYX_TOKEN, NYX_SHORTCUTS and NYX_ALIASES in the environment.

$script:NyxEsc = [char]27
$script:NyxBel = [char]7
$script:NyxToken = $env:NYX_TOKEN

function Nyx-Mark([string]$Body) {
    if (-not $script:NyxToken) { return }
    # The window title is the transport; Nyx consumes anything addressed to this pane's token
    # and never displays it.
    [Console]::Write($script:NyxEsc + "]2;nyx:" + $script:NyxToken + ":" + $Body + $script:NyxBel)
}

function Nyx-LoadTable([string]$Path) {
    $table = @{}
    if ($Path -and (Test-Path -LiteralPath $Path)) {
        foreach ($line in [System.IO.File]::ReadAllLines($Path)) {
            if ($line -eq '') { continue }
            $i = $line.IndexOf("`t")
            if ($i -lt 1) { continue }
            $table[$line.Substring(0, $i)] = $line.Substring($i + 1)
        }
    }
    return $table
}

$script:NyxShortcutPath = $env:NYX_SHORTCUTS
$script:NyxAliasPath = $env:NYX_ALIASES
$script:NyxShortcuts = Nyx-LoadTable $script:NyxShortcutPath
$script:NyxAliases = Nyx-LoadTable $script:NyxAliasPath
$script:NyxStamp = $null
$script:NyxDefinedAliases = @()

function Nyx-EncodePath([string]$Path) {
    # Percent-encode the UTF-8 *bytes*.
    #
    # ToCharArray walks UTF-16 code units, so this used to emit one escape per code unit: 'e-acute'
    # became %E9, a byte that is not valid UTF-8 on its own, and a CJK character became %4E2D --
    # four hex digits, because X2 is a minimum width and not a truncation -- which the decoder
    # reads as 'N' followed by a literal '2D'. Clink and bash both encode bytes; this is the one
    # that did not, and all three feed the same decoder.
    $sb = New-Object System.Text.StringBuilder
    foreach ($b in [System.Text.Encoding]::UTF8.GetBytes($Path)) {
        # Every unreserved character is ASCII, so testing the byte as a char is safe here.
        if ([char]$b -match '[A-Za-z0-9._~/-]') { [void]$sb.Append([char]$b) }
        else { [void]$sb.AppendFormat('%{0:X2}', $b) }
    }
    return $sb.ToString()
}

function Nyx-Refresh {
    # Re-read when the file changes, so editing config.toml takes effect in shells that are
    # already open instead of only in new ones.
    if (-not $script:NyxShortcutPath) { return }
    if (-not (Test-Path -LiteralPath $script:NyxShortcutPath)) { return }
    $stamp = (Get-Item -LiteralPath $script:NyxShortcutPath).LastWriteTimeUtc
    if ($stamp -ne $script:NyxStamp) {
        $script:NyxStamp = $stamp
        $script:NyxShortcuts = Nyx-LoadTable $script:NyxShortcutPath
        $script:NyxAliases = Nyx-LoadTable $script:NyxAliasPath
        Nyx-DefineAliases
    }
}

function Nyx-DefineAliases {
    # Withdraw the ones that are gone first. A reload only ever added, so an alias deleted from
    # config.toml stayed defined in every shell that was already open -- still shadowing the real
    # command it was named after, with nothing in the config to explain why.
    #
    # Only names this script defined are removed, which is what the tracking list is for: a
    # function the user wrote is not ours to withdraw.
    #
    # 'Function:\name', not 'function:global:name'. Set-Item honours the global: qualifier in a
    # provider path; Remove-Item does not -- it reports success and leaves the function exactly
    # where it was, so with -ErrorAction SilentlyContinue there is nothing at all to notice.
    foreach ($name in $script:NyxDefinedAliases) {
        if (-not $script:NyxAliases.ContainsKey($name)) {
            Remove-Item -LiteralPath ("Function:\" + $name) -Force -ErrorAction SilentlyContinue
        }
    }
    foreach ($name in $script:NyxAliases.Keys) {
        $value = $script:NyxAliases[$name]
        # A function, not Set-Alias: an alias cannot carry arguments, so "gs" -> "git status"
        # is not expressible as one.
        $body = "$value @args"
        Set-Item -Path ("function:global:" + $name) -Value ([ScriptBlock]::Create($body)) -Force
    }
    $script:NyxDefinedAliases = @($script:NyxAliases.Keys)
}
Nyx-DefineAliases

if (Get-Module -ListAvailable -Name PSReadLine) {
    Import-Module PSReadLine -ErrorAction SilentlyContinue

    # Ctrl+S is ForwardSearchHistory, which searches from the cursor towards the end of history --
    # at a prompt you are already at the end, so it can only ever answer "failed-fwd-i-search".
    # Ctrl+R does the search anyone actually wants. Unbound, PSReadLine ignores the key.
    Remove-PSReadLineKeyHandler -Chord 'Ctrl+s' -ErrorAction SilentlyContinue

    function Nyx-ExpandTokenBeforeCursor {
        $line = $null
        $cursor = 0
        [Microsoft.PowerShell.PSConsoleReadLine]::GetBufferState([ref]$line, [ref]$cursor)
        if ($null -eq $line -or $cursor -le 0) { return $false }

        # Walk back to the start of the word under the cursor.
        $start = $cursor
        while ($start -gt 0 -and -not [char]::IsWhiteSpace($line[$start - 1])) { $start-- }
        $len = $cursor - $start
        if ($len -le 0) { return $false }
        $token = $line.Substring($start, $len)

        $replacement = $null
        if ($script:NyxShortcuts.ContainsKey($token)) {
            $replacement = $script:NyxShortcuts[$token]
        } elseif ($start -eq 0 -and $script:NyxAliases.ContainsKey($token)) {
            # Aliases are commands, so only the first word of the line is one.
            $replacement = $script:NyxAliases[$token]
        }

        if ($null -eq $replacement) { return $false }
        [Microsoft.PowerShell.PSConsoleReadLine]::Replace($start, $len, $replacement)
        return $true
    }

    Set-PSReadLineKeyHandler -Chord Spacebar -BriefDescription 'NyxExpandSpace' -ScriptBlock {
        [void](Nyx-ExpandTokenBeforeCursor)
        [Microsoft.PowerShell.PSConsoleReadLine]::Insert(' ')
    }

    Set-PSReadLineKeyHandler -Chord Enter -BriefDescription 'NyxExpandEnter' -ScriptBlock {
        [void](Nyx-ExpandTokenBeforeCursor)
        Nyx-Mark 'C'
        [Microsoft.PowerShell.PSConsoleReadLine]::AcceptLine()
    }
}

# Wrap the existing prompt rather than replacing it, so a user's own prompt keeps working.
if (-not (Test-Path function:global:Nyx-InnerPrompt)) {
    if (Test-Path function:global:prompt) {
        ${function:global:Nyx-InnerPrompt} = ${function:global:prompt}
    } else {
        function global:Nyx-InnerPrompt { "PS $($executionContext.SessionState.Path.CurrentLocation)$('>' * ($nestedPromptLevel + 1)) " }
    }
}

function global:prompt {
    Nyx-Refresh
    Nyx-Mark 'A'
    $out = Nyx-InnerPrompt
    # Percent-encode the working directory: a Windows path contains ':' and '\', and ':' is the
    # message separator.
    Nyx-Mark ("B:cwd=" + (Nyx-EncodePath (Get-Location).Path))
    return $out
}

Nyx-Mark 'hello:v=1:caps=sigil,alias,marks'
"#;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::expand::handshake::{parse, Mark};

    /// Load the generated script in a real PowerShell and call one of its functions.
    ///
    /// The script that ships is what runs here, rather than a Rust restatement of it — a
    /// restatement can agree with itself while the shipped script does something else. Testing
    /// against the real thing on the machine is already how `win::registry`, `win::quake` and
    /// `win::shellicon` are covered, and PowerShell 5.1 is on every Windows install.
    fn run_in_powershell(call: &str) -> String {
        use std::io::Write;

        // Unique per call: these tests run in parallel threads of one process, so a directory
        // named after the pid alone has them overwriting each other's script.
        static NEXT: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(0);
        let n = NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!("nyx-psgen-{}-{n}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("nyx-init-test.ps1");

        let mut file = std::fs::File::create(&path).unwrap();
        // PowerShell 5.1 reads a .ps1 with no BOM as the ANSI code page, which would mangle every
        // non-ASCII character in the file before the script ever ran.
        file.write_all(&[0xEF, 0xBB, 0xBF]).unwrap();
        file.write_all(SCRIPT.as_bytes()).unwrap();
        file.write_all(b"\n").unwrap();
        file.write_all(call.as_bytes()).unwrap();
        file.write_all(b"\n").unwrap();
        drop(file);

        let output = std::process::Command::new("powershell.exe")
            .args(["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File"])
            .arg(&path)
            .output()
            .expect("powershell.exe");

        let _ = std::fs::remove_dir_all(&dir);
        assert!(
            output.status.success(),
            "the script failed to load: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        // The encoder emits nothing but ASCII, so the console's output code page cannot matter.
        String::from_utf8(output.stdout).expect("ASCII").trim().to_string()
    }

    fn single_quoted(s: &str) -> String {
        format!("'{}'", s.replace('\'', "''"))
    }

    #[test]
    fn a_deleted_alias_is_withdrawn_from_a_shell_that_is_already_open() {
        // `Nyx-DefineAliases` only ever added. An alias removed from config.toml stayed defined
        // in every shell that was already running — still shadowing the command it was named
        // after, with nothing left in the config to explain why.
        let out = run_in_powershell(
            r#"
$script:NyxAliases = @{ 'nyxtestgone' = 'echo gone'; 'nyxtestkept' = 'echo kept' }
Nyx-DefineAliases
$script:NyxAliases = @{ 'nyxtestkept' = 'echo kept' }
Nyx-DefineAliases
Write-Output ("gone=" + [bool](Get-Command nyxtestgone -ErrorAction SilentlyContinue))
Write-Output ("kept=" + [bool](Get-Command nyxtestkept -ErrorAction SilentlyContinue))
"#,
        );
        assert!(out.contains("gone=False"), "the deleted alias is still defined: {out}");
        assert!(out.contains("kept=True"), "the surviving alias was withdrawn too: {out}");
    }

    #[test]
    fn a_function_we_did_not_define_is_not_ours_to_withdraw() {
        // The removal pass walks only the names this script defined. A user function that
        // happens to share a name with an alias they just deleted must survive.
        let out = run_in_powershell(
            r#"
function global:nyxtestmine { 'mine' }
$script:NyxAliases = @{ }
Nyx-DefineAliases
Write-Output ("mine=" + [bool](Get-Command nyxtestmine -ErrorAction SilentlyContinue))
"#,
        );
        assert!(out.contains("mine=True"), "a user's own function was removed: {out}");
    }

    #[test]
    fn the_powershell_encoder_round_trips_through_the_decoder() {
        // The two halves of one protocol, checked against each other rather than each against
        // someone's expectation of the other. The encoder walked UTF-16 code units: an e-acute
        // became %E9 -- a byte that is not valid UTF-8 alone -- and a CJK character became %4E2D,
        // four hex digits, which the decoder reads as `N` followed by a literal `2D`.
        for original in [
            r"C:\Users\Nihil",
            r"C:\Users\Nihil\Desktop\Free Tibet",
            "C:\\caf\u{e9}",
            "C:\\\u{4e2d}\u{6587}\\dir",
            "C:\\emoji\\\u{1f600}",
            r"\\server\share\dir",
        ] {
            let encoded = run_in_powershell(&format!("Nyx-EncodePath {}", single_quoted(original)));
            assert!(encoded.is_ascii(), "{original:?} encoded to non-ASCII: {encoded:?}");
            assert!(!encoded.contains(':'), "{encoded:?} would split the message");

            let mark = parse(&format!("nyx:tok:B:cwd={encoded}"), "tok");
            assert_eq!(
                mark,
                Some(Mark::PromptEnd { cwd: Some(original.to_string()) }),
                "{original:?} encoded as {encoded:?}"
            );
        }
    }
    #[test]
    fn ctrl_s_is_left_unbound() {
        // PSReadLine binds Ctrl+S to ForwardSearchHistory by default, and at a prompt there is
        // nothing ahead to find -- the only thing it can say is "failed-fwd-i-search". Asked of a
        // real PSReadLine, because the default set is theirs to change and a chord name we
        // invented would remove nothing and report success.
        let out = run_in_powershell(
            r#"
$bound = Get-PSReadLineKeyHandler -Bound | Where-Object { $_.Key -eq 'Ctrl+s' }
if ($bound) { "bound:" + $bound.Function } else { "unbound" }
"#,
        );
        assert_eq!(out, "unbound");
    }
}
