//! The Git Bash init script.
//!
//! Loaded with `bash --rcfile <this>`, which *replaces* `~/.bashrc` — so it sources the user's
//! own files first, or a Git Bash launched through Nyx would silently lose their whole
//! environment.
//!
//! **Everything here runs in builtins.** Git for Windows is MSYS, where creating a process costs
//! about 44 ms — measured on this machine, by the tests below. A prompt hook is not a place that
//! can afford one, let alone four.

pub const SCRIPT: &str = r#"# Generated by Nyx. Edits are overwritten whenever the config changes.
#
# Loaded with: bash --rcfile <this file> -i
# --rcfile replaces ~/.bashrc, so the user's own startup files are sourced first.

if [ -f /etc/bash.bashrc ]; then . /etc/bash.bashrc; fi
if [ -f "$HOME/.bashrc" ]; then . "$HOME/.bashrc"; fi

__nyx_mark() {
    [ -z "$NYX_TOKEN" ] && return
    # The window title is the transport; Nyx consumes anything carrying this pane's token.
    printf '\033]2;nyx:%s:%s\007' "$NYX_TOKEN" "$1"
}

__nyx_load() {
    __nyx_keys=()
    __nyx_vals=()
    [ -r "$1" ] || return
    while IFS=$'\t' read -r key value; do
        [ -z "$key" ] && continue
        __nyx_keys+=("$key")
        __nyx_vals+=("$value")
    done < "$1"
}

__nyx_lookup() {
    local needle="$1" i
    for i in "${!__nyx_keys[@]}"; do
        if [ "${__nyx_keys[$i]}" = "$needle" ]; then
            printf '%s' "${__nyx_vals[$i]}"
            return 0
        fi
    done
    return 1
}

# The aliases this script defined last time it loaded the table.
__nyx_defined=()

__nyx_reload() {
    __nyx_load "$NYX_SHORTCUTS"
    __nyx_shortcut_keys=("${__nyx_keys[@]}")
    __nyx_shortcut_vals=("${__nyx_vals[@]}")
    __nyx_load "$NYX_ALIASES"
    __nyx_alias_keys=("${__nyx_keys[@]}")
    __nyx_alias_vals=("${__nyx_vals[@]}")

    local name i still

    # Withdraw what we defined last time and no longer define. A reload that only ever added
    # left an alias deleted from config.toml still defined in every shell already open, still
    # shadowing the command it was named after, with nothing left in the config to explain it.
    # Walking only our own list is what keeps an alias the *user* wrote from going with it.
    for name in "${__nyx_defined[@]}"; do
        still=
        for i in "${!__nyx_alias_keys[@]}"; do
            if [ "${__nyx_alias_keys[$i]}" = "$name" ]; then still=1; break; fi
        done
        [ -z "$still" ] && unalias "$name" 2>/dev/null
    done

    # Aliases as shell aliases: bash expands them itself, so no keybinding is needed for them.
    __nyx_defined=()
    for i in "${!__nyx_alias_keys[@]}"; do
        alias "${__nyx_alias_keys[$i]}"="${__nyx_alias_vals[$i]}"
        __nyx_defined+=("${__nyx_alias_keys[$i]}")
    done
}
__nyx_reload

# Percent-encode into __nyx_encoded. Builtins only, and deliberately so.
#
# The obvious spelling is a pipeline -- od -An -tx1 -v | tr -d ' \n' | sed 's/../%&/g' -- and
# that is what this used to be. It cost 120 ms of the 158 ms each prompt took, because MSYS
# process creation is ~44 ms and a command substitution around three commands is four of them.
# Every prompt, in a terminal whose whole premise is latency. This is ~1 ms, and ~0.2 ms for a
# path needing no escapes at all, which is most of them.
#
# LC_ALL=C is what makes ${s:i:1} a byte rather than a character, so a multi-byte character
# encodes as its UTF-8 bytes -- which is what the Rust decoder reads, and what the PowerShell and
# Clink halves of the same protocol send.
__nyx_encode() {
    local LC_ALL=C s="$1" i c hex
    __nyx_encoded=''
    case "$s" in
        *[!A-Za-z0-9._~/-]*) ;;
        *) __nyx_encoded="$s"; return ;;
    esac
    for (( i=0; i<${#s}; i++ )); do
        c="${s:i:1}"
        case "$c" in
            [A-Za-z0-9._~/-]) __nyx_encoded+="$c" ;;
            *) printf -v hex '%%%02X' "'$c"; __nyx_encoded+="$hex" ;;
        esac
    done
}

__nyx_expand_space() {
    local line="$READLINE_LINE" point="$READLINE_POINT"
    local head="${line:0:$point}"
    local word="${head##* }"
    if [ -n "$word" ]; then
        local i
        for i in "${!__nyx_shortcut_keys[@]}"; do
            if [ "${__nyx_shortcut_keys[$i],,}" = "${word,,}" ]; then
                local value="${__nyx_shortcut_vals[$i]}"
                local prefix="${head:0:$((point - ${#word}))}"
                READLINE_LINE="${prefix}${value}${line:$point}"
                READLINE_POINT=$((point - ${#word} + ${#value}))
                break
            fi
        done
    fi
    READLINE_LINE="${READLINE_LINE:0:$READLINE_POINT} ${READLINE_LINE:$READLINE_POINT}"
    READLINE_POINT=$((READLINE_POINT + 1))
}

if [ -n "$BASH_VERSION" ]; then
    bind -x '" ": __nyx_expand_space' 2>/dev/null
    # Ctrl+S is forward-search-history: it looks towards the end of history, and a fresh prompt
    # is already there, so it can only ever report a failed search. Ctrl+R is the useful one.
    bind -r '"\C-s"' 2>/dev/null
fi

__nyx_prompt() {
    __nyx_reload
    __nyx_mark 'A'
    # Percent-encode the working directory: ':' is the message separator. No command
    # substitution here either -- that alone would fork.
    __nyx_encode "$PWD"
    __nyx_mark "B:cwd=$__nyx_encoded"
}
PROMPT_COMMAND="__nyx_prompt${PROMPT_COMMAND:+; $PROMPT_COMMAND}"

__nyx_mark 'hello:v=1:caps=sigil,alias,marks'
"#;

#[cfg(test)]
mod tests {
    use std::sync::atomic::{AtomicU32, Ordering};

    use super::*;
    use crate::config::schema::{AliasMap, ShortcutConfig};
    use crate::expand::handshake::{parse, Mark};
    use crate::expand::shellgen::testing::{titles, without_titles};
    use crate::expand::shellgen::{alias_tsv, shortcut_tsv};
    use crate::expand::Tables;
    use crate::term::profile::PathStyle;

    const TOKEN: &str = "nyxtesttoken";
    const TARGET: &str = r"C:\Users\Nihil\Desktop\Free Tibet";

    struct Ran {
        /// Raw, because the marks are escape sequences in it.
        stdout: String,
        /// The same thing with the marks removed, which is what can be read by line.
        text: String,
    }

    fn tables() -> Tables {
        let shortcuts = vec![ShortcutConfig {
            id: "tibet".into(),
            label: "Free Tibet".into(),
            sigil: "@tibet".into(),
            path: TARGET.into(),
            icon: String::new(),
            color: None,
            order: 0,
        }];
        let mut aliases = AliasMap::new();
        aliases.insert("gs".into(), "git status".into());
        Tables::from_config(&shortcuts, &aliases).0
    }

    /// The expansion the TSV actually carries, POSIX quoting included.
    fn expansion() -> String {
        let tsv = shortcut_tsv(&tables(), PathStyle::Msys);
        tsv.trim_end()
            .split_once('\t')
            .expect("a sigil and an expansion")
            .1
            .to_string()
    }

    /// A path as this bash will accept it.
    ///
    /// MSYS reads `C:/dir/file` without complaint and is unreliable about `C:\dir\file`, which is
    /// what Rust hands out. Forward slashes cost nothing and avoid the question entirely.
    fn bashify(path: &std::path::Path) -> String {
        path.to_string_lossy().replace('\\', "/")
    }

    /// Run the script Nyx actually ships, in the real Git Bash, and return what it printed.
    ///
    /// The same shape as `powershell.rs` and `clink.rs`: the probe is a second file sourced after
    /// the init script, so it sees the functions the script defines rather than a copy of them.
    ///
    /// Returns `None` when Git for Windows is not installed, and says so on stderr rather than
    /// passing quietly — 0.2 is this project's own evidence about what a silent gate costs.
    fn run_in_bash(probe: &str) -> Option<Ran> {
        let Some(bash) = crate::term::detect::detect().git_bash else {
            eprintln!("SKIPPED: Git for Windows is not installed, so this test did not run.");
            return None;
        };

        static NEXT: AtomicU32 = AtomicU32::new(0);
        let n = NEXT.fetch_add(1, Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!("nyx-bashgen-{}-{n}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();

        // The files the script reads are the ones `regenerate` writes, so the format is exercised
        // rather than restated. `Msys` is the style a bash profile resolves to, so what the test
        // feeds it is a POSIX path, quoted the way the real table quotes it.
        let t = tables();
        let shortcut_file = dir.join("shortcuts.tsv");
        let alias_file = dir.join("aliases.tsv");
        std::fs::write(&shortcut_file, shortcut_tsv(&t, PathStyle::Msys)).unwrap();
        std::fs::write(&alias_file, alias_tsv(&t)).unwrap();

        let script = dir.join("nyx.bash");
        let probe_file = dir.join("probe.sh");
        std::fs::write(&script, SCRIPT.as_bytes()).unwrap();
        // `done=1` last: bash keeps going after most errors, so a probe that fell over halfway
        // would otherwise look like one whose assertions simply were not reached.
        std::fs::write(
            &probe_file,
            format!("{probe}\nprintf 'done=1\\n'\n").as_bytes(),
        )
        .unwrap();

        let output = std::process::Command::new(&bash)
            .arg("--rcfile")
            .arg(bashify(&script))
            .arg("-i")
            .arg(bashify(&probe_file))
            .current_dir(&dir)
            .env("NYX_TOKEN", TOKEN)
            .env("NYX_SHORTCUTS", bashify(&shortcut_file))
            .env("NYX_ALIASES", bashify(&alias_file))
            .output()
            .expect("bash.exe");

        let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
        let stderr = String::from_utf8_lossy(&output.stderr).into_owned();
        let _ = std::fs::remove_dir_all(&dir);

        assert!(
            stdout.contains("done=1"),
            "the script or the probe died partway.\nstdout:\n{stdout}\nstderr:\n{stderr}"
        );
        Some(Ran {
            text: without_titles(&stdout),
            stdout,
        })
    }

    fn field<'a>(out: &'a str, key: &str) -> &'a str {
        out.lines()
            .find_map(|l| l.strip_prefix(key))
            .unwrap_or_else(|| panic!("no {key:?} line in:\n{out}"))
    }

    #[test]
    fn the_space_binding_expands_the_word_before_the_cursor() {
        // `bind -x` hands the function the line in `READLINE_LINE` and the cursor in
        // `READLINE_POINT` and reads both back afterwards, so setting them is the whole of what
        // the key press does. What the press cannot be given here is a terminal — see the note
        // on `bind` in the module docs.
        let Some(ran) = run_in_bash(
            r#"
press() {
    READLINE_LINE="$1"; READLINE_POINT="$2"
    __nyx_expand_space
    printf '%s=[%s] point=%s\n' "$3" "$READLINE_LINE" "$READLINE_POINT"
}
press "cd @TiBeT" 9 mid
press "@tibet" 6 first
press "plain" 5 plain
press "" 0 empty
press "cd @tibet here" 9 midline
"#,
        ) else {
            return;
        };

        let want = expansion();
        assert_eq!(
            field(&ran.text, "mid="),
            format!("[cd {want} ] point={}", want.len() + 4)
        );
        assert_eq!(
            field(&ran.text, "first="),
            format!("[{want} ] point={}", want.len() + 1)
        );
        // A word that is not a shortcut is left alone and the space is still typed. If this ever
        // eats the space, the space bar is broken in Git Bash and only this test would say so.
        assert_eq!(field(&ran.text, "plain="), "[plain ] point=6");
        assert_eq!(field(&ran.text, "empty="), "[ ] point=1");
        // The cursor is not always at the end of the line: expanding has to keep what follows
        // it. Two spaces is right rather than a mistake — the key pressed was space, so the one
        // that was already there is still there.
        assert_eq!(
            field(&ran.text, "midline="),
            format!("[cd {want}  here] point={}", want.len() + 4)
        );
    }

    #[test]
    fn a_deleted_alias_is_withdrawn_from_a_shell_that_is_already_open() {
        // The same defect 2.10 found in the PowerShell half, which this half still had: a reload
        // only ever added, so an alias deleted from config.toml stayed defined in every bash
        // already open, still shadowing the command it was named after.
        let Some(ran) = run_in_bash(
            r#"
printf 'gone\techo gone\nkept\techo kept\n' > two.tsv
NYX_ALIASES="$PWD/two.tsv" __nyx_reload
alias mine='echo mine'
printf 'kept\techo kept\n' > one.tsv
NYX_ALIASES="$PWD/one.tsv" __nyx_reload
printf 'gone=%s\n' "$(alias gone >/dev/null 2>&1 && echo still-defined || echo withdrawn)"
printf 'kept=%s\n' "$(alias kept >/dev/null 2>&1 && echo defined || echo lost)"
printf 'mine=%s\n' "$(alias mine >/dev/null 2>&1 && echo defined || echo lost)"
"#,
        ) else {
            return;
        };

        assert_eq!(field(&ran.text, "gone="), "withdrawn");
        assert_eq!(
            field(&ran.text, "kept="),
            "defined",
            "the surviving alias went too"
        );
        // The list of what we defined is what keeps a user's own alias out of it.
        assert_eq!(
            field(&ran.text, "mine="),
            "defined",
            "a user's own alias was withdrawn"
        );
    }

    #[test]
    fn the_bash_encoder_round_trips_through_the_rust_decoder() {
        // The third half of one protocol written in three languages. A bash string is a byte
        // string only while the locale says so, which is what `LC_ALL=C` in `__nyx_encode` is
        // for: without it `${s:i:1}` is a *character* and a CJK path encodes to something the
        // decoder reads as mojibake.
        const PATHS: [&str; 6] = [
            "/c/Users/Nihil",
            "/c/Users/Nihil/Desktop/Free Tibet",
            "/c/caf\u{e9}",
            "/c/\u{4e2d}\u{6587}/dir",
            "/c/emoji/\u{1f600}",
            r"C:\Users\Nihil",
        ];

        let mut probe = String::new();
        for path in PATHS {
            // Single quotes: every path here is literal, and none of them contains one.
            probe.push_str(&format!(
                "__nyx_encode '{path}'; printf 'enc=%s\\n' \"$__nyx_encoded\"\n"
            ));
        }

        let Some(ran) = run_in_bash(&probe) else {
            return;
        };

        let encoded: Vec<&str> = ran
            .text
            .lines()
            .filter_map(|l| l.strip_prefix("enc="))
            .collect();
        assert_eq!(encoded.len(), PATHS.len(), "in:\n{}", ran.stdout);

        for (original, encoded) in PATHS.iter().zip(encoded) {
            assert!(
                encoded.is_ascii(),
                "{original:?} encoded to non-ASCII: {encoded:?}"
            );
            assert!(
                !encoded.contains(':'),
                "{encoded:?} would split the message"
            );
            assert_eq!(
                parse(&format!("nyx:{TOKEN}:B:cwd={encoded}"), TOKEN),
                Some(Mark::PromptEnd {
                    cwd: Some((*original).to_string())
                }),
                "{original:?} encoded as {encoded:?}"
            );
        }
    }

    #[test]
    fn the_greeting_and_the_prompt_marks_go_out_as_titles() {
        // The whole transport end to end in the real shell: printf writes an OSC 2, it survives
        // to the process's stdout, and `handshake::parse` accepts what comes back out.
        let Some(ran) = run_in_bash("__nyx_prompt\nprintf 'cwd=%s\\n' \"$PWD\"\n") else {
            return;
        };

        let titles = titles(&ran.stdout);
        let marks: Vec<Mark> = titles.iter().filter_map(|t| parse(t, TOKEN)).collect();

        assert!(
            matches!(marks.first(), Some(Mark::Hello { caps }) if caps.iter().any(|c| c == "sigil")),
            "no greeting; titles were {titles:?}"
        );
        assert!(
            marks.contains(&Mark::PromptStart),
            "no prompt mark: {marks:?}"
        );
        // `$PWD` in Git Bash is an MSYS path, so what comes back is `/c/...` and not `C:\...`.
        // Translating it is `win::paths`' job on this side, not the script's: doing it in bash
        // would mean `cygpath`, which is a process, and a process here costs 44 ms.
        let cwd = field(&ran.text, "cwd=");
        assert!(
            marks.contains(&Mark::PromptEnd {
                cwd: Some(cwd.to_string())
            }),
            "the working directory did not survive the round trip: {marks:?} wanted {cwd:?}"
        );
    }

    #[test]
    fn a_prompt_starts_no_processes() {
        // This is the finding, not a precaution. The encoder used to be
        // `od -An -tx1 -v | tr -d ' \n' | sed 's/../%&/g'` inside a command substitution: four
        // processes, and MSYS charges about 44 ms for each. Every prompt cost 158 ms — press
        // Enter on a blank line in a terminal built for latency and wait a sixth of a second.
        // Builtins bring it to about 5 ms.
        //
        // A timing assertion, because "did it fork" is not a question bash can be asked. The
        // threshold is four times under the old cost and twenty times over the new one, so it
        // takes a regression to a subprocess to trip it, not a slow machine.
        let Some(ran) = run_in_bash(
            r#"
export LC_ALL=C
if [ -z "$EPOCHREALTIME" ]; then printf 'us=unavailable\n'; else
    s=${EPOCHREALTIME/./}
    for i in {1..20}; do __nyx_prompt >/dev/null; done
    e=${EPOCHREALTIME/./}
    printf 'us=%s\n' "$(( (e - s) / 20 ))"
fi
"#,
        ) else {
            return;
        };

        let us = field(&ran.text, "us=");
        let Ok(us) = us.parse::<i64>() else {
            eprintln!("SKIPPED: this bash has no EPOCHREALTIME, so the prompt was not timed");
            return;
        };
        assert!(us > 0, "the clock went backwards: {us}");
        assert!(
            us < 40_000,
            "a prompt took {us} us; it forks something it did not used to"
        );
    }
}
